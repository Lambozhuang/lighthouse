"""A YouTube link becomes the video's transcript.

A video page has no article text to extract; what is worth filing is what was said. YouTube
publishes captions for most videos (written by the uploader, or generated by speech recognition),
and `youtube-transcript-api` reads them the way the YouTube player does. No API key, no download
of the video itself.

Limits: a video without captions cannot be filed, and YouTube turns away requests from addresses
it distrusts (mostly data centres; a home connection is normally fine).
"""

import asyncio
import re
from urllib.parse import parse_qs, urlsplit

import httpx
from youtube_transcript_api import (
    CouldNotRetrieveTranscript,
    FetchedTranscript,
    IpBlocked,
    RequestBlocked,
    TranscriptsDisabled,
    VideoUnavailable,
    YouTubeTranscriptApi,
)

from lighthouse.ingest.fetch import ExtractionError, FetchError, NetworkError, Page

VIDEO_ID = re.compile(r"[A-Za-z0-9_-]{11}")
HOSTS = {"youtube.com", "www.youtube.com", "m.youtube.com", "music.youtube.com"}
# Path prefixes that carry the id in the path: youtube.com/shorts/<id>, /embed/<id>, /live/<id>.
PATH_PREFIXES = ("shorts", "embed", "live", "v")
# Captions arrive as a few words per line. Lines are joined into paragraphs of about this many
# seconds, each starting with its timestamp, so a note can say where in the video something is.
PARAGRAPH_SECONDS = 60
TIMEOUT_SECONDS = 30


def video_id(url: str) -> str | None:
    """The video id if `url` is a link to one YouTube video, else None."""
    try:
        parts = urlsplit(url)
    except ValueError:
        return None
    if parts.scheme not in ("http", "https") or not parts.hostname:
        return None
    host = parts.hostname.lower()
    segments = [segment for segment in parts.path.split("/") if segment]
    candidate: str | None = None
    if host == "youtu.be" and segments:
        candidate = segments[0]
    elif host in HOSTS:
        if segments == ["watch"]:
            candidate = (parse_qs(parts.query).get("v") or [None])[0]
        elif len(segments) == 2 and segments[0] in PATH_PREFIXES:
            candidate = segments[1]
    return candidate if candidate and VIDEO_ID.fullmatch(candidate) else None


async def fetch_video(video: str) -> Page:
    """Title and transcript of the video with id `video`."""
    url = f"https://www.youtube.com/watch?v={video}"
    try:
        async with asyncio.timeout(TIMEOUT_SECONDS):
            # The library is synchronous (it uses `requests`), so it runs in a thread.
            transcript, title = await asyncio.gather(asyncio.to_thread(_transcript, video), _title(url))
    except TimeoutError:
        raise NetworkError("YouTube took too long to answer") from None
    text = format_transcript(transcript)
    if not text:
        raise ExtractionError("This video's captions are empty")
    return Page(url=url, title=title, text=text)


def _transcript(video: str) -> FetchedTranscript:
    try:
        # Whatever language the video is in. The list puts captions written by a person before
        # generated ones, so the first entry is the best there is.
        available = list(YouTubeTranscriptApi().list(video))
        if not available:
            raise ExtractionError("This video has no captions, so there is no text to file")
        return available[0].fetch()
    except TranscriptsDisabled:
        raise ExtractionError("This video has no captions, so there is no text to file") from None
    except VideoUnavailable:
        raise ExtractionError("This video is not available") from None
    except (IpBlocked, RequestBlocked):
        blocked = NetworkError("YouTube refused the request from this server; try again later")
        raise blocked from None
    except CouldNotRetrieveTranscript as exc:
        # Private or age-restricted videos, and whatever YouTube changes next.
        raise YouTubeError(f"Could not read this video's captions ({type(exc).__name__})") from exc


class YouTubeError(FetchError):
    pass


async def _title(url: str) -> str | None:
    """Video title from YouTube's oEmbed endpoint. Nice to have: None if it does not answer."""
    try:
        async with httpx.AsyncClient(timeout=10, trust_env=False) as client:
            response = await client.get("https://www.youtube.com/oembed", params={"url": url, "format": "json"})
            response.raise_for_status()
            data = response.json()
    except (httpx.HTTPError, ValueError):
        return None
    title, author = data.get("title"), data.get("author_name")
    if not isinstance(title, str) or not title:
        return None
    return f"{title} ({author})" if isinstance(author, str) and author else title


def format_transcript(transcript: FetchedTranscript) -> str:
    """Caption lines joined into paragraphs, each with the time it starts at: `[12:05] ...`."""
    paragraphs: list[str] = []
    words: list[str] = []
    started = 0.0
    for snippet in transcript.snippets:
        line = " ".join(snippet.text.split())
        if not line:
            continue
        if words and snippet.start - started >= PARAGRAPH_SECONDS:
            paragraphs.append(f"[{_clock(started)}] {' '.join(words)}")
            words = []
        if not words:
            started = snippet.start
        words.append(line)
    if words:
        paragraphs.append(f"[{_clock(started)}] {' '.join(words)}")
    return "\n\n".join(paragraphs)


def _clock(seconds: float) -> str:
    minutes, secs = divmod(int(seconds), 60)
    hours, minutes = divmod(minutes, 60)
    return f"{hours}:{minutes:02d}:{secs:02d}" if hours else f"{minutes}:{secs:02d}"
